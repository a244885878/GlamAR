  static MakeupLook _look(
    String id,
    String name,
    String subtitle,
    MakeupCategory category,
    String image,
    List<String> tags, {
    required Color skin,
    required Color blush,
    required Color shadow,
    required Color lip,
    required String lipProduct,
    required String blushProduct,
    required LipFinish finish,
    bool bold = false,
    bool soft = false,
    double blushDetail = 0.5,
  }) {
    final intensity = bold ? 0.78 : (soft ? 0.46 : 0.62);
    final prefix = switch (category) {
      MakeupCategory.korean => 'kr',
      MakeupCategory.japanese => 'jp',
      MakeupCategory.chinese => 'cn',
      MakeupCategory.western => 'us',
    };
    final index = image.split('-').last;
    return MakeupLook(
      id: id,
      name: name,
      subtitle: subtitle,
      category: category,
      imageAsset: 'assets/images/looks/$prefix-$index.jpg',
      tags: tags,
      complexion: MakeupLayerConfig(
        color: skin,
        intensity: soft ? 0.32 : 0.46,
        detail: bold ? 0.72 : 0.48,
        product: 'GlamAR · Adaptive Skin',
      ),
      blush: MakeupLayerConfig(
        color: blush,
        intensity: intensity * 0.72,
        detail: blushDetail,
        product: blushProduct,
      ),
      eyeshadow: MakeupLayerConfig(
        color: shadow,
        secondaryColor: shadow.withValues(alpha: 0.72),
        intensity: intensity * 0.68,
        detail: bold ? 0.74 : 0.5,
        product: '精选眼影 · ${subtitle.toUpperCase()}',
      ),
      brows: MakeupLayerConfig(
        color: const Color(0xFF49362F),
        intensity: soft ? 0.42 : 0.58,
        detail: soft ? 0.38 : 0.56,
        product: '植村秀 · Seal Brown',
      ),
      eyeliner: MakeupLayerConfig(
        color: category == MakeupCategory.korean || soft
            ? const Color(0xFF49302B)
            : const Color(0xFF241A1C),
        intensity: bold ? 0.82 : (soft ? 0.42 : 0.62),
        detail: bold ? 0.78 : 0.48,
        product: 'Kiss Me · Heroine Make',
      ),
      lips: MakeupLayerConfig(
        color: lip,
        intensity: intensity,
        detail: 0.5,
        product: lipProduct,
      ),
      lipFinish: finish,
    );
  }
